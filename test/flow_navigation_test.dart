/// 흐름마다 '다음' 으로 끝까지 가고, 화면 안 뒤로가기(←) 로 한 단계씩 되돌아오는지 (2026-11-06)
/// 가짜 서버: "METHOD 경로" → 응답. 없는 경로는 500 이고 [unknown] 에 남는다
class _Server implements HttpClientAdapter {
  final routes = <String, Object? Function(RequestOptions o)>{};
  final requests = <(String, String)>[];
  final unknown = <String>[];

  @override
  Future<ResponseBody> fetch(RequestOptions o, Stream<Uint8List>? s, Future<void>? c) async {
    requests.add((o.method, o.path));
    final route = routes['${o.method} ${o.path}'];
    if (route == null) unknown.add('${o.method} ${o.path}');
    final body = route == null ? {'message': '예상하지 못한 요청 ${o.method} ${o.path}'} : route(o);
    return ResponseBody.fromString(jsonEncode(body), route == null ? 500 : 200,
        headers: {Headers.contentTypeHeader: [Headers.jsonContentType]});
  }

  @override
  void close({bool force = false}) {}
}

