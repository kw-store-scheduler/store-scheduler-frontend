import 'preference.dart' show fromServerEnum, toServerEnum;

/// 근무표 주기 (O02)
enum ScheduleCycle { weekly, biweekly, monthly }

/// 예외일 분류 (O06)
enum ExceptionCategory {
  delivery('입고'),
  sale('세일 행사'),
  season('시즌'),
  holidayEve('공휴일 전날'),
  other('기타');

  const ExceptionCategory(this.label);
  final String label;
}

/// 역량 등급 (상·중·하)
enum SkillLevel {
  none('없음'),
  low('하'),
  mid('중'),
  high('상');

  const SkillLevel(this.label);
  final String label;
}

const weekdayNames = ['MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY'];
const weekdayLabels = ['월', '화', '수', '목', '금', '토', '일'];

String dateParam(DateTime d) =>
    '${d.year.toString().padLeft(4, '0')}-${d.month.toString().padLeft(2, '0')}-${d.day.toString().padLeft(2, '0')}';

/// "09:00:00" → "09:00"
String hhmm(String time) => time.length >= 5 ? time.substring(0, 5) : time;

/// GET /api/stores/industries 한 줄: 업종을 고르면 미리 만들어지는 역량·교대
class IndustryInfo {
  const IndustryInfo({required this.code, required this.label, required this.skills, required this.shifts});

  final String code; // CAFE, CLOTHING …
  final String label;
  final List<String> skills;
  final List<(String name, String start, String end)> shifts;

  factory IndustryInfo.fromJson(Map<String, dynamic> j) => IndustryInfo(
        code: j['code'] as String,
        label: j['label'] as String,
        skills: [for (final s in j['skills'] as List) s as String],
        shifts: [
          for (final s in j['shifts'] as List)
