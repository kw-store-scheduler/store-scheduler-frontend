import 'package:flutter/material.dart';
import '../../core/api_service.dart';
import '../../core/session.dart';
import '../../core/store_api.dart';
import '../../core/theme.dart';
import '../../models/store.dart';
import '../../widgets/thyme_step_app_bar.dart';
// 행님이 만들어두신 O03(교대·요일 인원) 화면으로 연결!
import 'o03_store_shift_setup_page.dart'; 

class ScheduleCyclePage extends StatefulWidget {
  const ScheduleCyclePage({super.key});

  @override
  State<ScheduleCyclePage> createState() => _ScheduleCyclePageState();
}

class _ScheduleCyclePageState extends State<ScheduleCyclePage> {
  int _selectedCycle = 3; // 1: 주간, 2: 2주, 3: 월간
  bool _saving = false;

  // 서버 기본값 (희망 마감 25일, 주기 시작 2일 전 9시 자동 생성). 로그인했으면 매장 설정으로 바꾼다
  int _deadlineDay = 25;
  int _daysBefore = 2;
  int _hour = 9;

  static const _cycles = {1: ScheduleCycle.weekly, 2: ScheduleCycle.biweekly, 3: ScheduleCycle.monthly};

  @override
  void initState() {
    super.initState();
    if (Session.instance.isLoggedIn) _load();
  }

  Future<void> _load() async {
    try {
      final store = await StoreApi().current();
      if (!mounted) return;
      setState(() {
        _deadlineDay = store.preferenceDeadlineDay;
        _daysBefore = store.autoGenerateDaysBefore;
        _hour = store.autoGenerateHour;
      });
    } on ApiException {
      // 기본값으로 안내만 보여 준다
    }
  }

  /// 주기를 저장하고 자동 생성을 켠다 (시안 O02: 희망 마감과 자동 생성 일정)
  Future<void> _next() async {
    if (Session.instance.isLoggedIn) {
      setState(() => _saving = true);
      try {
        await StoreApi().updateSettings(scheduleCycle: _cycles[_selectedCycle], autoGenerate: true);
      } on ApiException catch (e) {
        if (mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text(e.message)));
        return;
      } finally {
        if (mounted) setState(() => _saving = false);
      }
    }
    if (!mounted) return;
    Navigator.push(context, MaterialPageRoute(builder: (context) => const StoreShiftSetupPage()));
  }

  String get _startText {
    final next = DateTime(DateTime.now().year, DateTime.now().month + 1);
    return "${next.year}. ${next.month}";
  }

  String get _hourText => _hour < 12 ? "오전 ${_hour == 0 ? 12 : _hour}시" : "오후 ${_hour == 12 ? 12 : _hour - 12}시";

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: ThymeColor.bg,
      appBar: ThymeStepAppBar(step: 2, total: 6, group: '매장 등록', owner: true),
      body: SafeArea(
        child: Column(
          children: [
            Expanded(
              child: SingleChildScrollView(
                padding: const EdgeInsets.symmetric(horizontal: 24.0),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    const SizedBox(height: 12),
                    const Text("근무표를 얼마마다 만들까요?", style: TextStyle(fontSize: 26, fontWeight: FontWeight.bold, color: ThymeColor.text, height: 1.3)),
                    const SizedBox(height: 12),
                    Text("정해진 주기에 맞춰 직원들에게 희망 제출 알림이 가요.", style: TextStyle(fontSize: 14, color: ThymeColor.textSub)),
                    const SizedBox(height: 32),

                    _buildCycleOption(1, "주간 (7일)", "매주 근무표가 바뀌는 매장", _selectedCycle == 1),
                    const SizedBox(height: 12),
                    _buildCycleOption(2, "2주", "학기 시험 기간에 맞추기 좋아요", _selectedCycle == 2),
                    const SizedBox(height: 12),
                    _buildCycleOption(3, "월간", "가장 많이 써요 · 주말 부담을 4주 누적으로 배분", _selectedCycle == 3),
                    const SizedBox(height: 32),

                    // 하단 정보 박스
                    Container(
                        padding: const EdgeInsets.all(20),
                        decoration: BoxDecoration(color: ThymeColor.surfaceSub, borderRadius: BorderRadius.circular(16)),
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.start,
                          children: [
                            _buildInfoRow("적용 시작", _startText),
                            _buildInfoRow("희망 마감", "매달 $_deadlineDay일"),
                            _buildInfoRow("자동 생성", "주기 시작 $_daysBefore일 전 $_hourText"),
                            const SizedBox(height: 16),
                            const Divider(),
                            const SizedBox(height: 12),
                            if (_selectedCycle == 3)
                              Row(
                                crossAxisAlignment: CrossAxisAlignment.start,
                                children: [
                                  const Icon(Icons.circle, size: 6, color: ThymeColor.text),
                                  const SizedBox(width: 8),
                                  Expanded(child: Text("월간을 고르면 직원은 날짜별로 가능 여부를 체크해요. 지난달 패턴이 미리 채워져요.", style: TextStyle(fontSize: 13, color: ThymeColor.charcoal, height: 1.4))),
                                ],
                              ),
                          ],
                        ),
                      ),
                  ],
                ),
              ),
            ),
            
            Padding(
              padding: const EdgeInsets.all(24.0),
              child: SizedBox(
                width: double.infinity,
                child: FilledButton(onPressed: _saving ? null : _next, child: Text(_saving ? "저장 중…" : "다음")),
              ),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildCycleOption(int value, String title, String subtitle, bool isSelected) {
    return GestureDetector(
      onTap: () => setState(() => _selectedCycle = value),
      child: Container(
        padding: const EdgeInsets.all(20),
        decoration: BoxDecoration(
          color: isSelected ? ThymeColor.selectedSoft : ThymeColor.surface,
          border: Border.all(color: isSelected ? ThymeColor.text : ThymeColor.border, width: isSelected ? 2 : 1),
          borderRadius: BorderRadius.circular(16),
        ),
        child: Row(
          children: [
            Icon(isSelected ? Icons.radio_button_checked : Icons.radio_button_unchecked, color: isSelected ? ThymeColor.text : ThymeColor.disabled),
            const SizedBox(width: 16),
            Expanded(
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(title, style: TextStyle(fontSize: 16, fontWeight: FontWeight.bold, color: isSelected ? ThymeColor.text : ThymeColor.text)),
                  const SizedBox(height: 4),
                  Text(subtitle, style: TextStyle(fontSize: 13, color: ThymeColor.textSub)),
                ],
              ),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildInfoRow(String label, String value) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 12.0),
      child: Row(
        children: [
          SizedBox(width: 70, child: Text(label, style: TextStyle(color: ThymeColor.textSub, fontSize: 13, fontWeight: FontWeight.bold))),
          Expanded(child: Text(value, style: const TextStyle(color: ThymeColor.text, fontSize: 14, fontWeight: FontWeight.bold))),
        ],
      ),
    );
  }
}